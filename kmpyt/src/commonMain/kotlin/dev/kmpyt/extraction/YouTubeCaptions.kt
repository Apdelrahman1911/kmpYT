package dev.kmpyt.extraction

import dev.kmpyt.UrlPolicy
import kotlinx.coroutines.CancellationException
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.*

@Serializable enum class YouTubeCaptionFormat { WEBVTT, TTML, JSON3, TIMEDTEXT }
@Serializable data class YouTubeCaptionTrack(val sourceIndex: Int, val id: String?, val url: String,
    val languageCode: String?, val name: String?, val kind: String?, val isAutoGenerated: Boolean?,
    val isTranslatable: Boolean?) {
    override fun toString() = "YouTubeCaptionTrack(index=$sourceIndex,id=$id,language=$languageCode,url=${ResearchRedaction.url(url)})"
}
@Serializable data class YouTubeCaptionLanguage(val languageCode: String, val name: String?)
@Serializable data class YouTubeCaptionAudioTrack(val captionTrackIndices: List<Int>,
    val defaultCaptionTrackIndex: Int?, val hasDefaultTrack: Boolean?)
@Serializable data class YouTubeCaptionCatalogue(val tracks: List<YouTubeCaptionTrack>,
    val translationLanguages: List<YouTubeCaptionLanguage>, val audioTracks: List<YouTubeCaptionAudioTrack>,
    val defaultAudioTrackIndex: Int?, val diagnostics: List<String> = emptyList())
@Serializable data class YouTubeCaptionSegment(val text: String, val offsetMs: Long? = null)
@Serializable data class YouTubeCaptionCue(val startMs: Long, val endMs: Long, val text: String,
    val id: String? = null, val settings: String? = null, val segments: List<YouTubeCaptionSegment> = emptyList(),
    val windowId: Int? = null, val append: Boolean? = null)
@Serializable data class YouTubeCaptionDocument(val format: YouTubeCaptionFormat, val cues: List<YouTubeCaptionCue>,
    val diagnostics: List<String> = emptyList())
class YouTubeCaptionException(val code: String) : IllegalArgumentException(code)

/** Reads actual caption metadata and time/text responses; it never creates a caption URL or translation request. */
object YouTubeCaptions {
    const val MAX_CHARACTERS = 2_000_000
    const val MAX_CUES = 20_000
    const val MAX_CUE_CHARACTERS = 16_384
    private const val MAX_TIME = 604_800_000L

    fun catalogue(player: JsonObject, responseUrl: String): YouTubeCaptionCatalogue? {
        val renderer = player.obj("captions")?.obj("playerCaptionsTracklistRenderer") ?: return null
        val warnings = mutableListOf<String>()
        val rawTracks = renderer.array("captionTracks").orEmpty()
        if (rawTracks.size > 256) return YouTubeCaptionCatalogue(emptyList(), emptyList(), emptyList(), null, listOf("CAPTION_CATALOGUE_LIMIT"))
        val tracks = rawTracks.mapIndexedNotNull { index, element ->
            val track = element as? JsonObject ?: return@mapIndexedNotNull null
            val url = track.text("baseUrl")?.let { candidate -> runCatching {
                require(candidate.length <= 16_384 && candidate.none { it.isWhitespace() || it.code < 32 || it == '\\' })
                EmbeddedData.absolute(responseUrl, candidate).substringBefore('#').also { require(UrlPolicy.validate(it, allowLocalHttp = true) == null) }
            }.getOrNull() }
            if (url == null) { warnings += "CAPTION_TRACK_URL_INVALID"; return@mapIndexedNotNull null }
            val kind = track.text("kind")
            YouTubeCaptionTrack(index, track.text("vssId") ?: track.text("id"), url, track.text("languageCode"),
                label(track["name"]), kind, kind?.let { it == "asr" }, boolean(track, "isTranslatable"))
        }
        val languages = renderer.array("translationLanguages").orEmpty().take(512).mapNotNull { element ->
            val language = element as? JsonObject ?: return@mapNotNull null
            language.text("languageCode")?.let { YouTubeCaptionLanguage(it, label(language["languageName"])) }
        }
        if (renderer.array("translationLanguages").orEmpty().size > 512) warnings += "CAPTION_TRANSLATION_LIMIT"
        val rawAudioTracks = renderer.array("audioTracks").orEmpty()
        val audioTracks = rawAudioTracks.take(256).mapNotNull { element ->
            val track = element as? JsonObject ?: return@mapNotNull null
            val indices = track.array("captionTrackIndices").orEmpty().mapNotNull { (it as? JsonPrimitive)?.intOrNull?.takeIf { value -> value in rawTracks.indices } }
            YouTubeCaptionAudioTrack(indices, track.number("defaultCaptionTrackIndex")?.takeIf { it in 0L until rawTracks.size.toLong() }?.toInt(), boolean(track, "hasDefaultTrack"))
        }
        if (rawAudioTracks.size > 256) warnings += "CAPTION_AUDIO_TRACK_LIMIT"
        if (audioTracks.size != minOf(rawAudioTracks.size, 256)) warnings += "CAPTION_AUDIO_TRACKS_INVALID"
        return YouTubeCaptionCatalogue(tracks, languages, audioTracks,
            renderer.number("defaultAudioTrackIndex")?.takeIf { rawAudioTracks.size == audioTracks.size && it in 0L until audioTracks.size.toLong() }?.toInt(), warnings.distinct())
    }

    fun parse(body: String, format: YouTubeCaptionFormat? = null): YouTubeCaptionDocument {
        if (body.length !in 1..MAX_CHARACTERS) throw YouTubeCaptionException("CAPTION_SIZE_LIMIT")
        val content = body.removePrefix("\uFEFF").trimStart()
        val actual = format ?: when {
            content.startsWith("WEBVTT") -> YouTubeCaptionFormat.WEBVTT
            content.startsWith("<") -> if (Regex("<(?:[A-Za-z_][\\w.-]*:)?(?:transcript|timedtext)(?:\\s|>)").containsMatchIn(content))
                YouTubeCaptionFormat.TIMEDTEXT else YouTubeCaptionFormat.TTML
            content.startsWith("{") -> YouTubeCaptionFormat.JSON3
            else -> throw YouTubeCaptionException("CAPTION_FORMAT_UNSUPPORTED")
        }
        return try {
            val cues = when (actual) {
                YouTubeCaptionFormat.WEBVTT -> webVtt(content)
                YouTubeCaptionFormat.TTML -> ttml(content)
                YouTubeCaptionFormat.JSON3 -> json3(content)
                YouTubeCaptionFormat.TIMEDTEXT -> timedText(content)
            }
            require(cues.size <= MAX_CUES)
            YouTubeCaptionDocument(actual, cues, if (cues.isEmpty()) listOf("CAPTION_NO_CUES") else emptyList())
        } catch (cancelled: CancellationException) { throw cancelled }
        catch (failure: YouTubeCaptionException) { throw failure }
        catch (_: Exception) { throw YouTubeCaptionException("CAPTION_INVALID_OR_UNSUPPORTED_DATA") }
    }

    /** Public timedtext's legacy transcript (seconds) and srv3 paragraph/segment (milliseconds) forms. */
    private fun timedText(body: String): List<YouTubeCaptionCue> {
        if (Regex("<!DOCTYPE|<!ENTITY", RegexOption.IGNORE_CASE).containsMatchIn(body))
            throw YouTubeCaptionException("CAPTION_XML_DECLARATION_UNSUPPORTED")
        val root = ManifestXml.parse(body)
        if (root.name == "transcript") {
            require(root.text.isBlank() && root.children.all { it.name == "text" })
            return root.children.map { node ->
                require(node.children.isEmpty())
                val start = decimal(requireNotNull(node.attributes["start"]), 1000)
                val duration = decimal(requireNotNull(node.attributes["dur"]), 1000)
                cue(start, start + duration, node.text)
            }
        }
        require(root.name == "timedtext" && root.attributes["format"] in setOf(null, "3"))
        val container = requireNotNull(root.child("body"))
        require(container.text.isBlank() && container.children.all { it.name in setOf("p", "w") })
        return container.all("p").map { node ->
            val start = requireNotNull(node.attributes["t"]).toLong()
            val duration = requireNotNull(node.attributes["d"]).toLong()
            require(start in 0..MAX_TIME && duration in 1..MAX_TIME - start)
            val segments = if (node.children.isEmpty()) listOf(YouTubeCaptionSegment(node.text)) else {
                require(node.text.isBlank() && node.children.all { it.name == "s" && it.children.isEmpty() })
                node.children.map { segment ->
                    val offset = segment.attributes["t"]?.toLong()?.also { require(it in 0..duration) }
                    YouTubeCaptionSegment(segment.text, offset)
                }
            }
            require(segments.size <= 4096)
            val append = node.attributes["a"]?.also { require(it in setOf("0", "1")) }?.let { it == "1" }
            val window = node.attributes["w"]?.toInt()?.also { require(it >= 0) }
            cue(start, start + duration, segments.joinToString("") { it.text }).copy(
                segments = segments, append = append, windowId = window)
        }
    }

    private fun webVtt(body: String): List<YouTubeCaptionCue> {
        val lines = body.replace("\r\n", "\n").replace('\r', '\n').split('\n')
        require(lines.first().matches(Regex("WEBVTT(?:[ \\t].*)?")))
        val cues = mutableListOf<YouTubeCaptionCue>(); var i = 1
        while (i < lines.size && lines[i].isNotBlank()) {
            if (lines[i].startsWith("X-TIMESTAMP-MAP")) throw YouTubeCaptionException("CAPTION_TIMESTAMP_MAP_UNSUPPORTED")
            i++
        }
        while (i < lines.size) {
            if (lines[i].isBlank()) { i++; continue }
            if (Regex("NOTE(?:$|[ \\t].*)").matches(lines[i]) || lines[i] in setOf("STYLE", "REGION")) {
                while (i < lines.size && lines[i].isNotBlank()) i++
                continue
            }
            var id: String? = null
            if (!lines[i].contains("-->")) { id = lines[i++]; require(i < lines.size) }
            val timing = Regex("^([^\\s]+)\\s+-->\\s+([^\\s]+)(?:[ \\t]+(.*))?$").matchEntire(lines[i++]) ?: error("Invalid cue timing")
            val start = clock(timing.groupValues[1]); val end = clock(timing.groupValues[2])
            val text = mutableListOf<String>()
            while (i < lines.size && lines[i].isNotBlank()) text += lines[i++]
            val plain = entities(text.joinToString("\n").replace(Regex("<[^>]{0,1024}>"), ""), html = true)
            cues += cue(start, end, plain, id, timing.groupValues[3].takeIf { it.isNotEmpty() })
            require(cues.size <= MAX_CUES)
        }
        return cues
    }

    private fun json3(body: String): List<YouTubeCaptionCue> {
        val root = Json.parseToJsonElement(body).jsonObject
        val events = root.array("events") ?: error("Missing caption events")
        require(events.size <= MAX_CUES)
        return events.mapNotNull { element ->
            val event = element as? JsonObject ?: error("Invalid caption event")
            val raw = (event["segs"] ?: return@mapNotNull null) as? JsonArray ?: error("Invalid caption segments") // Position/style/window events contain no text.
            require(raw.size <= 4096)
            if (raw.isEmpty()) return@mapNotNull null
            val segments = raw.map { item ->
                val segment = item as? JsonObject ?: error("Invalid caption segment")
                val text = (segment["utf8"] as? JsonPrimitive)?.takeIf { it.isString }?.content ?: error("Missing caption segment text")
                require(text.length <= MAX_CUE_CHARACTERS)
                val offset = jsonNumber(segment, "tOffsetMs")?.also { require(it in 0..MAX_TIME) }
                YouTubeCaptionSegment(text, offset)
            }
            val start = jsonNumber(event, "tStartMs") ?: error("Missing caption start")
            val duration = jsonNumber(event, "dDurationMs") ?: error("Missing caption duration")
            require(start in 0..MAX_TIME && duration in 1..MAX_TIME - start)
            segments.forEach { require(it.offsetMs == null || it.offsetMs <= duration) }
            val append = jsonNumber(event, "aAppend")?.also { require(it in 0..1) }?.let { it == 1L }
            cue(start, start + duration, segments.joinToString("") { it.text }).copy(segments = segments,
                windowId = jsonNumber(event, "wWinId")?.also { require(it in 0..Int.MAX_VALUE) }?.toInt(), append = append)
        }
    }

    private data class XmlFrame(val name: String, val start: Long, val end: Long?, val preserve: Boolean)
    private fun ttml(body: String): List<YouTubeCaptionCue> {
        if (Regex("<!DOCTYPE|<!ENTITY", RegexOption.IGNORE_CASE).containsMatchIn(body)) throw YouTubeCaptionException("CAPTION_XML_DECLARATION_UNSUPPORTED")
        val stack = mutableListOf<XmlFrame>(); val cues = mutableListOf<YouTubeCaptionCue>()
        var i = 0; var rootSeen = false; var frameRate: Double? = null; var tickRate: Double? = null
        var active: XmlFrame? = null; var activeId: String? = null; var text = StringBuilder()
        while (i < body.length) {
            if (body[i] != '<') {
                val end = body.indexOf('<', i).takeIf { it >= 0 } ?: body.length
                if (active != null) { text.append(entities(body.substring(i, end))); require(text.length <= MAX_CUE_CHARACTERS) }
                else if (stack.isEmpty()) require(body.substring(i, end).isBlank())
                i = end; continue
            }
            if (body.startsWith("<!--", i)) { i = body.indexOf("-->", i + 4).also { require(it >= 0) } + 3; continue }
            if (body.startsWith("<?", i)) { i = body.indexOf("?>", i + 2).also { require(it >= 0) } + 2; continue }
            require(!body.startsWith("<!", i))
            var end = i + 1; var quote: Char? = null
            while (end < body.length) {
                val c = body[end]
                if (quote != null) { if (c == quote) quote = null }
                else if (c in "\"'") quote = c else if (c == '>') break
                require(end - i <= MAX_CUE_CHARACTERS); end++
            }
            require(end < body.length)
            val tag = body.substring(i + 1, end).trim(); i = end + 1
            if (tag.startsWith('/')) {
                val name = tag.drop(1).trim().substringAfter(':')
                val frame = stack.removeLastOrNull() ?: error("Unexpected XML close")
                require(frame.name == name)
                if (name == "p") {
                    require(active == frame)
                    val plain = if (frame.preserve) text.toString() else text.toString().split('\n').joinToString("\n") { it.replace(Regex("[ \\t\\r]+"), " ").trim() }.trim()
                    cues += cue(frame.start, requireNotNull(frame.end), plain, activeId)
                    require(cues.size <= MAX_CUES); active = null; activeId = null; text = StringBuilder()
                }
                continue
            }
            val closed = tag.endsWith('/')
            val raw = if (closed) tag.dropLast(1).trimEnd() else tag
            val fullName = raw.takeWhile { !it.isWhitespace() }
            require(Regex("[A-Za-z_][A-Za-z0-9_.:-]*").matches(fullName))
            val name = fullName.substringAfter(':'); val attributes = attributes(raw.drop(fullName.length))
            if (!rootSeen) {
                require(name == "tt"); rootSeen = true
                if (attributes["timeBase"]?.let { it != "media" } == true || attributes["dropMode"]?.let { it != "nonDrop" } == true)
                    throw YouTubeCaptionException("CAPTION_TTML_TIMEBASE_UNSUPPORTED")
                if ("subFrameRate" in attributes) throw YouTubeCaptionException("CAPTION_TTML_SUBFRAMES_UNSUPPORTED")
                frameRate = attributes["frameRate"]?.toDoubleOrNull()?.also { require(it.isFinite() && it in 1.0..240.0) }
                attributes["frameRateMultiplier"]?.let { multiplier ->
                    val parts = multiplier.trim().split(Regex("\\s+")); require(parts.size == 2)
                    val numerator = parts[0].toDouble(); val denominator = parts[1].toDouble()
                    require(numerator.isFinite() && denominator.isFinite() && numerator > 0 && denominator > 0)
                    frameRate = requireNotNull(frameRate) * numerator / denominator
                    require(requireNotNull(frameRate).isFinite() && requireNotNull(frameRate) in 0.001..240.0)
                }
                tickRate = attributes["tickRate"]?.toDoubleOrNull()?.also { require(it.isFinite() && it > 0 && it <= 1_000_000) }
            } else require(stack.isNotEmpty())
            if (attributes["timeContainer"] == "seq") throw YouTubeCaptionException("CAPTION_TTML_SEQUENTIAL_TIMING_UNSUPPORTED")
            if (name == "br") {
                require(closed && active != null)
                if (listOf("begin", "end", "dur").any { it in attributes }) throw YouTubeCaptionException("CAPTION_TTML_TIMED_SPAN_UNSUPPORTED")
                text.append('\n'); continue
            }
            if (active != null && listOf("begin", "end", "dur").any { it in attributes }) throw YouTubeCaptionException("CAPTION_TTML_TIMED_SPAN_UNSUPPORTED")
            val parent = stack.lastOrNull()
            val start = (parent?.start ?: 0) + (attributes["begin"]?.let { time(it, frameRate, tickRate) } ?: 0)
            // TTML's explicit end, duration, and inherited container end all clip
            // the active interval; choosing only end would silently extend a cue.
            val stop = listOfNotNull(attributes["end"]?.let { (parent?.start ?: 0) + time(it, frameRate, tickRate) },
                attributes["dur"]?.let { start + time(it, frameRate, tickRate) }, parent?.end).minOrNull()
            require(start in 0..MAX_TIME && (stop == null || stop in start + 1..MAX_TIME))
            val preserve = attributes["space"]?.let { require(it in setOf("preserve", "default")); it == "preserve" } ?: parent?.preserve ?: false
            if (active != null && preserve != active.preserve) throw YouTubeCaptionException("CAPTION_TTML_SPAN_SPACE_UNSUPPORTED")
            val frame = XmlFrame(name, start, stop, preserve)
            if (name == "p") { require(active == null && stop != null && !closed); active = frame; activeId = attributes["id"] }
            if (!closed) { require(stack.size < 128); stack += frame }
        }
        require(rootSeen && stack.isEmpty() && active == null)
        return cues
    }

    private fun attributes(body: String): Map<String, String> {
        val result = mutableMapOf<String, String>(); var position = 0
        val pattern = Regex("\\s+([A-Za-z_][A-Za-z0-9_.:-]*)\\s*=\\s*(['\"])(.*?)\\2", RegexOption.DOT_MATCHES_ALL)
        while (position < body.length) {
            if (body.substring(position).isBlank()) break
            val match = pattern.find(body, position) ?: error("Invalid XML attribute")
            require(match.range.first == position)
            val name = match.groupValues[1].substringAfter(':')
            require(name !in result && result.size < 128)
            result[name] = entities(match.groupValues[3]); position = match.range.last + 1
        }
        return result
    }

    private fun time(value: String, frameRate: Double?, tickRate: Double?): Long {
        Regex("^(\\d+(?:\\.\\d+)?)(h|m|s|ms|f|t)$").matchEntire(value)?.let { match ->
            val amount = match.groupValues[1]
            return when (match.groupValues[2]) {
                "h" -> decimal(amount, 3_600_000); "m" -> decimal(amount, 60_000)
                "s" -> decimal(amount, 1000); "ms" -> decimal(amount, 1)
                else -> {
                    val rate = requireNotNull(if (match.groupValues[2] == "f") frameRate else tickRate)
                    require(rate.isFinite() && rate > 0)
                    (amount.toDouble() * 1000 / rate).also { require(it.isFinite() && it in 0.0..MAX_TIME.toDouble()) }.toLong()
                }
            }
        }
        Regex("^(\\d+):(\\d{2}):(\\d{2}):(\\d{2})(?:\\.(\\d+))?$").matchEntire(value)?.let { match ->
            val rate = requireNotNull(frameRate)
            require(rate.isFinite() && rate > 0)
            val frames = match.groupValues[4].toLong()
            require(frames < rate)
            if (match.groupValues[5].isNotEmpty()) throw YouTubeCaptionException("CAPTION_TTML_SUBFRAMES_UNSUPPORTED")
            return clock("${match.groupValues[1]}:${match.groupValues[2]}:${match.groupValues[3]}") + (frames * 1000 / rate).toLong()
        }
        return clock(value)
    }

    private fun clock(value: String): Long {
        val parts = value.split(':'); require(parts.size in 2..3)
        val hours = if (parts.size == 3) parts[0].toLong() else 0
        val minutes = parts[parts.lastIndex - 1].toLong(); val seconds = decimal(parts.last(), 1000)
        require(hours >= 0 && minutes in 0..59 && seconds in 0..59_999 && hours <= MAX_TIME / 3_600_000)
        return (hours * 3_600_000 + minutes * 60_000 + seconds).also { require(it <= MAX_TIME) }
    }

    private fun decimal(value: String, multiplier: Long): Long {
        require(Regex("\\d+(?:\\.\\d{1,9})?").matches(value))
        val parts = value.split('.'); val whole = parts[0].toLong(); require(whole <= MAX_TIME / multiplier)
        val fraction = parts.getOrNull(1)?.let { digits -> var denominator = 1L; repeat(digits.length) { denominator *= 10 }; digits.toLong() * multiplier / denominator } ?: 0
        return (whole * multiplier + fraction).also { require(it <= MAX_TIME) }
    }

    private fun cue(start: Long, end: Long, text: String, id: String? = null, settings: String? = null): YouTubeCaptionCue {
        require(start in 0..MAX_TIME && end in start + 1..MAX_TIME && text.length <= MAX_CUE_CHARACTERS)
        return YouTubeCaptionCue(start, end, text, id, settings)
    }

    private fun entities(value: String, html: Boolean = false): String {
        val result = StringBuilder(); var i = 0
        while (i < value.length) {
            if (value[i] != '&') { result.append(value[i++]); continue }
            val end = value.indexOf(';', i + 1)
            if (html && end !in i + 2..minOf(value.lastIndex, i + 16)) { result.append(value[i++]); continue }
            require(end in i + 2..minOf(value.lastIndex, i + 16))
            val entity = value.substring(i + 1, end)
            val literal = when (entity) {
                "amp" -> "&"; "lt" -> "<"; "gt" -> ">"; "quot" -> "\""; "apos" -> "'"
                "nbsp" -> if (html) "\u00a0" else null; "lrm" -> if (html) "\u200e" else null; "rlm" -> if (html) "\u200f" else null
                else -> null
            }
            if (literal != null) result.append(literal) else {
                if (html && !entity.startsWith('#')) { result.append(value.substring(i, end + 1)); i = end + 1; continue }
                val number = if (entity.startsWith("#x", true)) entity.drop(2).toInt(16) else if (entity.startsWith('#')) entity.drop(1).toInt() else error("Unknown entity")
                require(number in 1..0x10ffff && number !in 0xd800..0xdfff && (number >= 32 || number in listOf(9, 10, 13)))
                if (number <= 0xffff) result.append(number.toChar()) else { val code = number - 0x10000; result.append((0xd800 + (code shr 10)).toChar()); result.append((0xdc00 + (code and 1023)).toChar()) }
            }
            i = end + 1
        }
        return result.toString()
    }

    private fun boolean(value: JsonObject, key: String) = (value[key] as? JsonPrimitive)?.booleanOrNull
    /** json3 times/window IDs are JSON integer fields, not optional guessed strings. */
    private fun jsonNumber(value: JsonObject, key: String): Long? {
        val element = value[key] ?: return null
        if (element == JsonNull) return null
        val primitive = element as? JsonPrimitive ?: error("Invalid caption integer")
        require(!primitive.isString)
        return primitive.longOrNull ?: error("Invalid caption integer")
    }
    private fun label(value: JsonElement?): String? = (value as? JsonObject)?.let { obj ->
        obj.text("simpleText") ?: obj.array("runs")?.mapNotNull { (it as? JsonObject)?.text("text") }?.joinToString("")
    }
}

/** Fetches only the actual metadata-supplied URL; redirects and response substitutions are explicit failures. */
class YouTubeCaptionClient(private val transport: ResearchTransport,
    private val accessContract: (YouTubeCaptionTrack) -> Boolean = { false }) {
    suspend fun load(track: YouTubeCaptionTrack, format: YouTubeCaptionFormat? = null): YouTubeCaptionDocument {
        val authorized = try { accessContract(track) }
        catch (cancelled: CancellationException) { throw cancelled }
        catch (_: Exception) { false }
        if (!authorized) throw YouTubeCaptionException("CAPTION_ACCESS_NOT_AUTHORIZED")
        if (UrlPolicy.validate(track.url, allowLocalHttp = true) != null) throw YouTubeCaptionException("CAPTION_URL_INVALID")
        val response = try { transport.execute(ResearchRequest("GET", track.url,
            mapOf("Accept" to "text/vtt, application/ttml+xml, application/json, text/xml"), stage = "youtube-captions")) }
        catch (cancelled: CancellationException) { throw cancelled }
        catch (_: Exception) { throw YouTubeCaptionException("CAPTION_HTTP_FAILED") }
        if (response.status !in 200..299) throw YouTubeCaptionException("CAPTION_HTTP_${response.status}")
        if (response.url != track.url) throw YouTubeCaptionException("CAPTION_RESPONSE_IDENTITY_MISMATCH")
        val mime = response.headers.entries.firstOrNull { it.key.equals("content-type", true) }?.value?.substringBefore(';')?.trim()?.lowercase()
        if (!mime.isNullOrBlank() && mime !in setOf("text/vtt", "application/ttml+xml", "application/json", "text/xml", "application/xml", "text/plain"))
            throw YouTubeCaptionException("CAPTION_HTTP_TYPE_UNSUPPORTED")
        return YouTubeCaptions.parse(response.body, format)
    }
}
