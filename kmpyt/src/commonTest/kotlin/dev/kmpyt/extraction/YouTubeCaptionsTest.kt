package dev.kmpyt.extraction

import kotlinx.coroutines.test.runTest
import kotlinx.serialization.json.*
import kotlin.test.*

class YouTubeCaptionsTest {
    private val context = ExtractionContext("https://www.youtube.com/watch?v=ABCDEFGHIJK", "http://127.0.0.1:8123/watch", 1_000)
    private fun player(extra: String) = """{"videoDetails":{"videoId":"ABCDEFGHIJK","title":"Owned caption parser test"},$extra}"""
    private fun catalogue(extra: String) = assertNotNull(YouTubeCaptions.catalogue(Json.parseToJsonElement(
        """{"captions":{"playerCaptionsTracklistRenderer":{$extra}}}""").jsonObject, context.responseUrl))

    @Test fun preservesActualCaptionIdentityLanguageDefaultsAndSignedUrlBytes() {
        val item = catalogue(""""captionTracks":[{"baseUrl":"/captions?v=ABCDEFGHIJK&token=a%2Fb%2bc&x=x+y","vssId":"a.en","languageCode":"en","name":{"runs":[{"text":"English "},{"text":"automatic"}]},"kind":"asr","isTranslatable":true},{"baseUrl":"/manual","languageCode":"fr","name":{"simpleText":"French"}}],"translationLanguages":[{"languageCode":"de","languageName":{"simpleText":"German"}}],"audioTracks":[{"captionTrackIndices":[0,1],"defaultCaptionTrackIndex":1,"hasDefaultTrack":true}],"defaultAudioTrackIndex":0""")
        assertEquals("http://127.0.0.1:8123/captions?v=ABCDEFGHIJK&token=a%2Fb%2bc&x=x+y", item.tracks[0].url)
        assertEquals("a.en", item.tracks[0].id); assertEquals("en", item.tracks[0].languageCode)
        assertEquals("English automatic", item.tracks[0].name); assertEquals(true, item.tracks[0].isAutoGenerated)
        assertEquals(true, item.tracks[0].isTranslatable); assertNull(item.tracks[1].isAutoGenerated)
        assertNull(item.tracks[1].id); assertEquals(listOf(0, 1), item.audioTracks.single().captionTrackIndices)
        assertEquals(1, item.audioTracks.single().defaultCaptionTrackIndex); assertEquals(0, item.defaultAudioTrackIndex)
        assertEquals(YouTubeCaptionLanguage("de", "German"), item.translationLanguages.single())
        assertFalse(item.tracks[0].toString().contains("a%2Fb"))
    }

    @Test fun invalidTrackUrlsAndOverflowingDefaultIndicesDoNotFabricateValidEntries() {
        val item = catalogue(""""captionTracks":[{"baseUrl":"https://user:private@caption.example/subs"},{"baseUrl":"javascript:alert(1)"},{"baseUrl":"/actual"}],"audioTracks":[{"captionTrackIndices":[0,2,900],"defaultCaptionTrackIndex":4294967296}],"defaultAudioTrackIndex":999""")
        assertEquals(listOf(2), item.tracks.map { it.sourceIndex })
        assertEquals(listOf(0, 2), item.audioTracks.single().captionTrackIndices, "Indices refer to the source catalogue, not a reordered invented array")
        assertNull(item.audioTracks.single().defaultCaptionTrackIndex); assertNull(item.defaultAudioTrackIndex)
        assertEquals(listOf("CAPTION_TRACK_URL_INVALID"), item.diagnostics)
        assertNull(YouTubeCaptions.catalogue(JsonObject(emptyMap()), context.responseUrl))
    }

    @Test fun providerReadsActualAudioDefaultLabelCodecLoudnessAndColorFieldsWithoutInferringHdr() {
        val result = YouTubeProvider().parse(context, player(""""streamingData":{"adaptiveFormats":[{"itag":140,"url":"/audio.m4a","mimeType":"audio/mp4; codecs=\"mp4a.40.2\"","audioTrack":{"id":"en.4","displayName":"English original","audioIsDefault":true,"languageCode":"en"},"audioQuality":"AUDIO_QUALITY_MEDIUM","audioSampleRate":"44100","audioChannels":2,"isDrc":false,"loudnessDb":-4.25},{"itag":137,"url":"/video.mp4","mimeType":"video/mp4; codecs=\"avc1.640028\"","colorInfo":{"primaries":"COLOR_PRIMARIES_BT709","transferCharacteristics":"COLOR_TRANSFER_CHARACTERISTICS_BT709","matrixCoefficients":"COLOR_MATRIX_COEFFICIENTS_BT709"}}]},"captions":{"playerCaptionsTracklistRenderer":{"captionTracks":[{"baseUrl":"/subs","vssId":".en","languageCode":"en"}]}}"""))
        val media = result.media.single(); val audio = media.representations[0]
        assertEquals("en", audio.audioLanguage); assertEquals("English original", audio.audioDisplayName)
        assertEquals(true, audio.audioIsDefault); assertEquals("AUDIO_QUALITY_MEDIUM", audio.audioQuality)
        assertEquals("mp4a.40.2", audio.codecs); assertEquals(false, audio.isDrc); assertEquals(-4.25, audio.loudnessDb)
        assertEquals(44_100, audio.audioSampleRate); assertEquals(2, audio.audioChannels)
        assertEquals("COLOR_PRIMARIES_BT709", media.representations[1].colorInfo?.primaries)
        assertNull(media.representations[1].isHdr, "BT709 and a video quality label are not an actual isHdr boolean")
        assertEquals(".en", media.captions?.tracks?.single()?.id)
    }

    @Test fun displayNameIsNotTreatedAsLanguageAndMissingSourceFieldsStayUnknown() {
        val format = YouTubeProvider().parse(context, player(""""streamingData":{"adaptiveFormats":[{"itag":140,"url":"/audio","mimeType":"audio/mp4","audioTrack":{"displayName":"English (United States)"}}]}""")).media.single().representations.single()
        assertNull(format.audioLanguage); assertEquals("English (United States)", format.audioDisplayName)
        assertNull(format.audioIsDefault); assertNull(format.audioQuality); assertNull(format.isDrc)
        assertNull(format.loudnessDb); assertNull(format.colorInfo); assertNull(format.isHdr)
    }

    @Test fun parsesWebVttActualCueTimingIdentifiersSettingsAndEntities() {
        val document = YouTubeCaptions.parse("""
            WEBVTT

            NOTE authored subtitle test
            ignored commentary

            STYLE
            ::cue { color: lime; }

            cue-one
            00:01.250 --> 00:03.500 align:start position:10%
            <v Speaker>First &amp; second &#x1F642;</v>
            literal A & B

            00:01:03.000 --> 00:01:04.250
            <b>Second</b>
        """.trimIndent())
        assertEquals(YouTubeCaptionFormat.WEBVTT, document.format); assertEquals(2, document.cues.size)
        assertEquals(1_250L, document.cues[0].startMs); assertEquals(3_500L, document.cues[0].endMs)
        assertEquals("cue-one", document.cues[0].id); assertEquals("align:start position:10%", document.cues[0].settings)
        assertEquals("First & second 🙂\nliteral A & B", document.cues[0].text)
        assertEquals(63_000L, document.cues[1].startMs)
    }

    @Test fun webVttRejectsMissingReversedAndUnsupportedManifestTimeMapping() {
        listOf("WEBVTT\n\n00:01.000 --> 00:00.999\nbad", "WEBVTT\n\nmissing timing",
            "WEBVTT\n\n00:99.000 --> 00:99.999\nbad").forEach { body -> assertFailsWith<YouTubeCaptionException> { YouTubeCaptions.parse(body) } }
        assertEquals("CAPTION_TIMESTAMP_MAP_UNSUPPORTED", assertFailsWith<YouTubeCaptionException> {
            YouTubeCaptions.parse("WEBVTT\nX-TIMESTAMP-MAP=LOCAL:00:00:00.000,MPEGTS:90000\n\n00:01.000 --> 00:02.000\nTest")
        }.code)
    }

    @Test fun parsesTtmlParentRelativeTimingClippingAndExplicitBreaks() {
        val result = YouTubeCaptions.parse("""<?xml version="1.0"?><tt xmlns="http://www.w3.org/ns/ttml"><body begin="1s" end="6s"><div begin="500ms"><p xml:id="line" begin="500ms" dur="3s"> First <span> &amp; second </span><br/> next </p><p begin="3s" dur="4s">Clipped</p></div></body></tt>""")
        assertEquals(YouTubeCaptionFormat.TTML, result.format)
        assertEquals(YouTubeCaptionCue(2_000, 5_000, "First & second\nnext", "line"), result.cues[0])
        assertEquals(4_500L, result.cues[1].startMs); assertEquals(6_000L, result.cues[1].endMs)
    }

    @Test fun ttmlUsesActualFrameAndTickRatesAndPreservesRequestedSpace() {
        val result = YouTubeCaptions.parse("""<tt xmlns:ttp="http://www.w3.org/ns/ttml#parameter" ttp:frameRate="30" ttp:frameRateMultiplier="1 1" ttp:tickRate="100"><body><p begin="00:00:01:15" dur="30f" xml:space="preserve">  frame  </p><p begin="300t" dur="50t">tick</p></body></tt>""")
        assertEquals(1_500L, result.cues[0].startMs); assertEquals(2_500L, result.cues[0].endMs)
        assertEquals("  frame  ", result.cues[0].text); assertEquals(3_000L, result.cues[1].startMs)
        assertEquals(3_500L, result.cues[1].endMs)
    }

    @Test fun ttmlExplicitEndDurationAndInheritedContainerEachClipActualCueInterval() {
        val result = YouTubeCaptions.parse("""<tt><body begin="1s" end="8s"><p begin="1s" end="6s" dur="2s">Duration clips end</p><p begin="2s" end="4s" dur="6s">End clips duration</p><p begin="5s" end="20s" dur="10s">Parent clips both</p></body></tt>""")
        assertEquals(listOf(2_000L, 3_000L, 6_000L), result.cues.map { it.startMs })
        assertEquals(listOf(4_000L, 5_000L, 8_000L), result.cues.map { it.endMs })
    }

    @Test fun unsupportedSubframesTimebasesAndTimedBreaksNeverBecomeGuessedTimings() {
        val forbidden = listOf("""<tt xmlns:ttp="urn:ttml" ttp:frameRate="30"><p begin="00:00:01:15.5" dur="1s">Subframe needs a real rate</p></tt>""",
            """<tt xmlns:ttp="urn:ttml" ttp:subFrameRate="2"><p begin="1s" dur="1s">Unsupported rate</p></tt>""",
            """<tt xmlns:ttp="urn:ttml" ttp:timeBase="clock"><p begin="1s" dur="1s">Wall clock</p></tt>""",
            """<tt xmlns:ttp="urn:ttml" ttp:dropMode="dropNTSC"><p begin="1s" dur="1s">Drop timing</p></tt>""",
            """<tt><p begin="1s" dur="2s">Before<br begin="500ms"/>after</p></tt>""")
        forbidden.forEach { assertFailsWith<YouTubeCaptionException> { YouTubeCaptions.parse(it) } }
    }

    @Test fun unsupportedXmlConstructsNeverResolveExternalEntitiesOrInventTiming() {
        val forbidden = listOf("""<!DOCTYPE tt [<!ENTITY leak SYSTEM "file:///private">]><tt><body><p begin="1s" dur="1s">&leak;</p></body></tt>""",
            "<transcript><text start=\"1\" dur=\"2\">Legacy XML is a different contract</text></transcript>",
            "<tt><body><p>missing timing</p></body></tt>", "<tt><body><p begin=\"1f\" dur=\"1s\">missing actual frame rate</p></body></tt>",
            "<tt><body><p begin=\"1s\" dur=\"1s\"><span begin=\"1ms\">unsupported timed span</span></p></body></tt>",
            "<tt><body timeContainer=\"seq\"><p begin=\"1s\" dur=\"1s\">unsupported sequence</p></body></tt>",
            "<tt><body><p begin=\"1s\" dur=\"1s\">&unknown;</p></body></tt>", "garbage<tt></tt>")
        forbidden.forEach { body -> val failure = assertFailsWith<YouTubeCaptionException> { YouTubeCaptions.parse(body, YouTubeCaptionFormat.TTML) }
            assertFalse(failure.message.orEmpty().contains("file:///private")); assertFalse(failure.message.orEmpty().contains("&leak;")) }
    }

    @Test fun json3RetainsActualWordOffsetsRollingWindowMetadataAndLiteralText() {
        val result = YouTubeCaptions.parse("""{"events":[{"tStartMs":0,"wWinId":1,"dDurationMs":5000},{"tStartMs":1000,"dDurationMs":2200,"wWinId":1,"aAppend":1,"segs":[{"utf8":"A &amp; ","tOffsetMs":0},{"utf8":"word","tOffsetMs":350}]}]}""")
        val cue = result.cues.single(); assertEquals(1_000L, cue.startMs); assertEquals(3_200L, cue.endMs)
        assertEquals("A &amp; word", cue.text); assertEquals(1, cue.windowId); assertEquals(true, cue.append)
        assertEquals(listOf(0L, 350L), cue.segments.map { it.offsetMs })
    }

    @Test fun json3RefusesMissingDurationInvalidOffsetsAndNegativeWindowRatherThanReturningSuccess() {
        listOf("""{"tStartMs":1,"segs":[{"utf8":"no duration"}]}""", """{"tStartMs":1,"dDurationMs":100,"segs":[{"utf8":"late","tOffsetMs":101}]}""",
            """{"tStartMs":-1,"dDurationMs":100,"segs":[{"utf8":"negative"}]}""", """{"tStartMs":1,"dDurationMs":100,"wWinId":-1,"segs":[{"utf8":"negative window"}]}""")
            .forEach { event -> assertFailsWith<YouTubeCaptionException> { YouTubeCaptions.parse("{\"events\":[$event]}") } }
        assertEquals(listOf("CAPTION_NO_CUES"), YouTubeCaptions.parse("{\"events\":[]}").diagnostics)
    }

    @Test fun malformedJson3OptionalIntegerTypesAndNonTextSegmentsFailInsteadOfBecomingAbsent() {
        listOf(""""wWinId":"bad","segs":[{"utf8":"text"}]""", """"aAppend":true,"segs":[{"utf8":"text"}]""",
            """"segs":[{"utf8":"text","tOffsetMs":"bad"}]""", """"segs":[{"utf8":"text","tOffsetMs":{}}]""",
            """"segs":[{"utf8":true}]""", """"segs":{}""").forEach { fields ->
            assertFailsWith<YouTubeCaptionException> { YouTubeCaptions.parse("""{"events":[{"tStartMs":1,"dDurationMs":100,$fields}]}""") }
        }
    }

    @Test fun malformedAudioCatalogueCannotRemapASourceDefaultIndexToAnotherTrack() {
        val item = catalogue(""""captionTracks":[{"baseUrl":"/en"}],"audioTracks":[false,{"captionTrackIndices":[0]}],"defaultAudioTrackIndex":0""")
        assertNull(item.defaultAudioTrackIndex)
        assertEquals(listOf("CAPTION_AUDIO_TRACKS_INVALID"), item.diagnostics)
    }

    @Test fun boundsBodyCueSizeAndTimeAndSanitizesParserFailures() {
        assertEquals("CAPTION_SIZE_LIMIT", assertFailsWith<YouTubeCaptionException> { YouTubeCaptions.parse(" ".repeat(YouTubeCaptions.MAX_CHARACTERS + 1)) }.code)
        assertFailsWith<YouTubeCaptionException> { YouTubeCaptions.parse("WEBVTT\n\n00:00.000 --> 00:01.000\n" + "x".repeat(YouTubeCaptions.MAX_CUE_CHARACTERS + 1)) }
        val failure = assertFailsWith<YouTubeCaptionException> { YouTubeCaptions.parse("{\"events\":[{\"private-token\":\"secret\"}") }
        assertFalse(failure.message.orEmpty().contains("secret"))
    }

    @Test fun captionAccessContractDeniesBeforeTransportAndExactResponseIdentityIsRequired() = runTest {
        val track = YouTubeCaptionTrack(0, ".en", "http://127.0.0.1:8123/caption?token=private", "en", null, null, null, null)
        var requests = 0
        val transport = ResearchTransport { request -> requests++; ResearchResponse(request.url, 200, "WEBVTT\n\n00:00.000 --> 00:01.000\nOwned") }
        assertEquals("CAPTION_ACCESS_NOT_AUTHORIZED", assertFailsWith<YouTubeCaptionException> { YouTubeCaptionClient(transport).load(track) }.code)
        assertEquals(0, requests)
        val callbackFailure = assertFailsWith<YouTubeCaptionException> {
            YouTubeCaptionClient(transport) { error("private callback-token value") }.load(track)
        }
        assertEquals("CAPTION_ACCESS_NOT_AUTHORIZED", callbackFailure.code)
        assertFalse(callbackFailure.message.orEmpty().contains("callback-token")); assertEquals(0, requests)
        assertEquals("Owned", YouTubeCaptionClient(transport) { it.url == track.url }.load(track).cues.single().text)
        val mismatch = YouTubeCaptionClient(ResearchTransport { ResearchResponse("http://127.0.0.1:8123/other", 200, "WEBVTT") }) { true }
        assertEquals("CAPTION_RESPONSE_IDENTITY_MISMATCH", assertFailsWith<YouTubeCaptionException> { mismatch.load(track) }.code)
    }
}
